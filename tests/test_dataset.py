import torch
from torch.utils.data import DataLoader

from data.dataset import ValueFormerWindowDataset, build_balanced_sampler, episode_level_split
from data.synthetic import generate_synthetic_dataset
from models.dinov3_encoder import FrozenDinoV3Encoder


def test_episode_level_split_has_no_overlap():
    episodes = generate_synthetic_dataset(n_expert_success=6, n_rollout_success=4, n_rollout_fail=4, seed=0)
    train, val = episode_level_split(episodes, val_fraction=0.25, seed=0)
    train_ids = {e.episode_id for e in train}
    val_ids = {e.episode_id for e in val}
    assert train_ids.isdisjoint(val_ids)
    assert len(train_ids) + len(val_ids) == len(episodes)


def test_window_dataset_shapes_and_left_padding():
    episodes = generate_synthetic_dataset(n_expert_success=2, n_rollout_success=2, n_rollout_fail=2, seed=1)
    enc = FrozenDinoV3Encoder(use_real_dinov3=False)
    ds = ValueFormerWindowDataset(episodes, enc, seq_len=16, gamma=0.99, n_stages=6)
    sample = ds[0]  # frame_idx=0 of the first episode -> fully left-padded window
    assert sample["vision"].shape == (16, 6144)
    assert sample["state"].shape == (16, 14)
    assert sample["time_feat"].shape == (16, 2)
    assert torch.equal(sample["vision"][0], sample["vision"][1])  # left-pad repeats frame 0


def test_balanced_sampler_skips_empty_groups_and_covers_present_groups():
    episodes = generate_synthetic_dataset(n_expert_success=3, n_rollout_success=2, n_rollout_fail=2, seed=2)
    enc = FrozenDinoV3Encoder(use_real_dinov3=False)
    ds = ValueFormerWindowDataset(episodes, enc, seq_len=16, gamma=0.99, n_stages=6)
    group_ids = ds.group_ids()
    assert "expert-fail" not in set(group_ids)  # never generated by default

    sampler = build_balanced_sampler(group_ids, num_samples=200)
    loader = DataLoader(ds, batch_size=32, sampler=sampler)
    seen_groups = set()
    for batch in loader:
        seen_groups.update(batch["group"])
    assert seen_groups == {"expert-success", "rollout-success", "rollout-fail"}
